import { expect, it } from '@effect/vitest';
import { Effect, Schema } from 'effect';
import { EventNotificationSettings } from './notifications/settings.ts';
import {
  base32Decode,
  base32Encode,
  decodeSettingsCode,
  encodeSettingsCode,
} from './settingsCode.ts';
import { DesktopSettings, SettingsAccount } from './settingsDocument.ts';
import { PortableViewPreferences } from './viewPreferences.ts';

const PortableDocument = Schema.Struct({
  accounts: Schema.Array(SettingsAccount).check(Schema.isMaxLength(4)),
  desktop: DesktopSettings,
  eventNotifications: EventNotificationSettings,
  version: Schema.Literal(1),
  view: PortableViewPreferences,
});

it.effect.prop(
  'settings codes preserve portable preferences and omit desktop settings and Google display titles',
  { document: PortableDocument },
  ({ document }) =>
    Effect.gen(function* () {
      const decoded = yield* decodeSettingsCode(encodeSettingsCode(document));
      expect(decoded.desktop).toBeUndefined();
      expect(decoded.version).toBe(1);
      expect(decoded.eventNotifications).toEqual(document.eventNotifications);
      expect(decoded.view).toEqual(document.view);
      expect(decoded.accounts).toEqual(
        document.accounts.map((account) =>
          account.kind === 'google'
            ? {
                ...account,
                ...(account.calendars
                  ? { calendars: account.calendars.map((calendar) => ({ ...calendar, title: '' })) }
                  : {}),
                ...(account.taskLists
                  ? { taskLists: account.taskLists.map((list) => ({ ...list, title: '' })) }
                  : {}),
              }
            : account,
        ),
      );
    }),
  { arbitrary: { size: 12 } },
);

it.prop(
  'base32 round trips generated byte arrays including partial final groups',
  {
    bytes: Schema.Array(Schema.Int.check(Schema.isBetween({ maximum: 255, minimum: 0 }))).check(
      Schema.isMaxLength(256),
    ),
  },
  ({ bytes }) => {
    const input = Uint8Array.from(bytes);
    expect(base32Decode(base32Encode(input))).toEqual(input);
  },
);
